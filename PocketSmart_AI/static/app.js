function renderResult(data) {
  const box = document.getElementById("result");
  if (!box) return;
  const items = data.recommendations || [];
  box.innerHTML = `
    <div class="result-box">
      <h2>${data.summary || "Suggested options"}</h2>
      <p class="muted">${data.message || "Generated by PocketSmart AI"}</p>
      ${items.map(x => `
        <div class="recommendation">
          <div>
            <h3>${x.title}</h3>
            <p>${x.reason || ""}</p>
            <small>${x.platform || "Platform"}</small>
          </div>
          <strong>₹${Number(x.price || 0).toLocaleString("en-IN")}</strong>
        </div>`).join("")}
    </div>`;
}

document.querySelectorAll(".planner-form").forEach(form => {
  form.addEventListener("submit", async (e) => {
    e.preventDefault();
    const button = form.querySelector("button");
    button.disabled = true;
    button.textContent = "Generating...";
    try {
      const endpoint = form.dataset.endpoint;
      const isMultipart = form.enctype === "multipart/form-data";
      let response;
      if (isMultipart) {
        response = await fetch(endpoint, {method: "POST", body: new FormData(form)});
      } else {
        const body = Object.fromEntries(new FormData(form).entries());
        if (body.budget) body.budget = Number(body.budget);
        if (body.guests) body.guests = Number(body.guests);
        response = await fetch(endpoint, {
          method: "POST",
          headers: {"Content-Type": "application/json"},
          body: JSON.stringify(body)
        });
      }
      const data = await response.json();
      if (!response.ok) throw new Error(data.detail || "Request failed");
      renderResult(data);
    } catch (err) {
      document.getElementById("result").innerHTML =
        `<div class="error">${err.message}</div>`;
    } finally {
      button.disabled = false;
      button.textContent = "Generate Recommendations";
    }
  });
});

async function loadHistory() {
  const box = document.getElementById("history");
  if (!box) return;
  try {
    const r = await fetch("/api/history");
    if (!r.ok) {
      box.innerHTML = "<p>Login to view recommendation history.</p>";
      return;
    }
    const rows = await r.json();
    box.innerHTML = rows.length ? rows.map(x => `
      <div class="card">
        <h3>${x.category} — ₹${Number(x.budget).toLocaleString("en-IN")}</h3>
        <p>${new Date(x.created_at).toLocaleString()}</p>
      </div>`).join("") : "<p>No recommendations yet.</p>";
  } catch {
    box.innerHTML = "<p>Could not load history.</p>";
  }
}
loadHistory();
